import { expect, test } from "@playwright/test";

// START DOCKER BEFORE RUNNING TESTS
test("user can create an anonymous account, create a room, send a message, then delete it", async ({
  page,
}) => {
  const now = Date.now(); // name/content
  const username = `User ${now}`; // 20 Characters long
  const roomName = `Test Room ${now}`;
  const messageContent = `Test message ${now}`;

  //open homepage
  await page.goto("/");

  //create anonymous user
  await page.getByRole("textbox").fill(username);
  await page.getByRole("button", { name: "Create User" }).click();

  //successful user creation causes room form to appear
  await expect(page.getByRole("button", { name: "Create Room" })).toBeVisible();

  //create chatroom
  await page.getByRole("textbox").fill(roomName);
  await page.getByRole("button", { name: "Create Room" }).click();

  //room creation navigates to URL containing generated UUID
  await expect(page).toHaveURL(/\/chatrooms\/[0-9a-f-]+$/); // UUID expression generated by codex

  //confirm that the room loaded
  await expect(page.getByRole("heading", { name: roomName })).toBeVisible();

  //empty room should display empty state
  await expect(page.getByText("No messages yet.")).toBeVisible();
  
  //create a message
  await page.getByPlaceholder("Type your message...")
    .fill(messageContent);
  await page.getByRole("button", { name: "Send" }).click();

  // assign created message locator to value because it will be reused
  const createdMessage = page.getByText(
    `content: ${messageContent}`,
    { exact: true },
  );

  // confirm message appears
  await expect(createdMessage).toBeVisible();
  // reload, then confirm message still appears
  await page.reload();
  await expect(createdMessage).toBeVisible();

  // delete message
  await page.getByRole("button", { name: "Delete" }).click();

  await expect(createdMessage).not.toBeVisible();
  await expect(page.getByText("No messages yet.")).toBeVisible();

  // check if delete persists after reload
  await page.reload();
  await expect(createdMessage).not.toBeVisible();
  await expect(page.getByText("No messages yet.")).toBeVisible();
});
